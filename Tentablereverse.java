public class Tentablereverse {
    public static void main(String[] args) {
        int i;
        int j;
        for(i = 10; i<= 10; i++){
            for(j = 10; j>=1; j--){
                int multiplication = i*j;
                System.out.println("The Multiplication Table is: " + multiplication);
            }
            System.out.println();
        }

    }
}
